#!/usr/bin/env python3
"""
Final-week fp32/fp64 comparison driver (binary-exact mesh).

One protocol, applied identically to both precisions. Only the icoFoam binary
differs (DP app build vs the local SP build). The mesh is generated by the DP
blockMesh in both cases -- mesh FILES are precision-independent ASCII; the SP
solver still recomputes its own geometry in single precision, which is exactly
where the empty-patch face-area bug would bite, so this remains a valid test.

Verification: every fp32 run is checked for the presence of
`Solving for Ux` and `Solving for Uy` at (essentially) every timestep. A run
missing them is marked INVALID and its timing/accuracy must not be reported.

Usage:
  python3 run_case.py --label t_fp64_r1 --precision fp64 --steps 512
  python3 run_case.py --label acc_fp32 --precision fp32 --endTime 2.5 --psolver GAMG
"""
import argparse, csv, json, os, re, shutil, subprocess, time
import numpy as np

HERE      = os.path.dirname(os.path.abspath(__file__))
TEMPLATE  = os.path.join(HERE, "template")
CASES     = os.path.join(HERE, "cases")
RESULTS   = os.path.join(HERE, "results_final.csv")
DP_LAUNCH = os.environ.get("FOAM_LAUNCH", "/Applications/OpenFOAM-v2512.app/Contents/Resources/etc/openfoam")
SP_BASHRC = os.environ.get("FOAM_SP_BASHRC", "/Volumes/OpenFOAM-SP/OpenFOAM-v2512-SP/etc/bashrc")
DP_CTL_BASHRC = os.environ.get("FOAM_DP_CTL_BASHRC", "/Volumes/OpenFOAM-SP/OpenFOAM-v2512-SP/etc/bashrc.dp")  # control: same tree/flags, DP

# ---- geometry / physics (fixed; H and W must NOT change -- they set Re_H) ---
L, H, W = 1.0, 0.1, 0.01
NU, UMAX = 1.0e-3, 1.5
DT   = 0.00048828125        # 2^-11 -> Co = 0.375 on nx=512
NX, NY = 512, 128              # powers of two -> binary-exact spacings

PSOLVER_BLOCKS = {
    "GAMG": "        solver           GAMG;\n"
            "        smoother         GaussSeidel;\n"
            "        nCellsInCoarsestLevel 10;",
    "PCG":  "        solver           PCG;\n"
            "        preconditioner   DIC;",
}

CSV_FIELDS = ["label", "precision", "psolver", "ptol", "nx", "ny", "cells", "dt",
              "steps_requested", "steps_done", "endTime", "Co_max",
              "ux_lines", "uy_lines", "valid",
              "wall_s", "exec_s", "s_per_step", "peak_rss_MiB",
              "p_iters_median", "p_iters_capped", "p_finalres_median",
              "cont_err_local", "cont_err_cumulative",
              "U_peak_outlet", "U_centre_outlet", "U_mean_outlet",
              "err_max_pct_Umax", "err_L2_pct_Umax", "tau_w_over_rho"]


def gen_case(label, psolver, ptol, endTime, writeInterval):
    case = os.path.join(CASES, label)
    if os.path.exists(case):
        shutil.rmtree(case)
    shutil.copytree(TEMPLATE, case)
    subs = {"__NX__": str(NX), "__NY__": str(NY),
            "__DELTAT__": repr(DT), "__ENDTIME__": repr(endTime),
            "__WRITEINTERVAL__": repr(writeInterval),
            "__PSOLVERBLOCK__": PSOLVER_BLOCKS[psolver], "__PTOL__": ptol}
    for rel in ("system/blockMeshDict", "system/controlDict", "system/fvSolution"):
        p = os.path.join(case, rel); s = open(p).read()
        for k, v in subs.items():
            s = s.replace(k, v)
        open(p, "w").write(s)
    return case


def run(case, precision, cmd, capture_mem=False):
    """Run an OpenFOAM command; returns (returncode, wall_seconds, peak_rss_MiB).
    With capture_mem, `/usr/bin/time -l` stats go to log.time (kept separate from
    the solver log so the log stays clean and parseable)."""
    if capture_mem:
        inner = (f"cd '{case}' && /usr/bin/time -l {cmd} "
                 f"> log.icoFoam 2> log.time")
    else:
        inner = f"cd '{case}' && {cmd}"
    if precision == "fp32":
        argv = ["bash", "-c", f"source '{SP_BASHRC}' >/dev/null 2>&1 && {inner}"]
    elif precision == "fp64ctl":          # locally-built DP: same toolchain as SP
        argv = ["bash", "-c", f"source '{DP_CTL_BASHRC}' >/dev/null 2>&1 && {inner}"]
    else:
        argv = [DP_LAUNCH, "bash", "-c", inner]
    t0 = time.time()
    r = subprocess.run(argv, capture_output=True, text=True)
    wall = time.time() - t0
    rss = float("nan")
    tf = os.path.join(case, "log.time")
    if capture_mem and os.path.exists(tf):
        m = re.search(r"(\d+)\s+maximum resident set size", open(tf, errors="replace").read())
        if m:
            rss = int(m.group(1)) / (1024 * 1024)  # bytes -> MiB
    return r.returncode, wall, rss


def parse_log(path):
    """Timestep count, Ux/Uy solve counts, p-solver stats, Courant, continuity."""
    n_t = ux = uy = 0
    p_iters, p_fin = [], []
    co_max = exec_s = float("nan")
    cont_local = cont_cum = float("nan")
    with open(path, errors="replace") as f:
        for line in f:
            if line.startswith("Time = "):
                n_t += 1
            elif "Solving for Ux" in line:
                ux += 1
            elif "Solving for Uy" in line:
                uy += 1
            elif "Solving for p" in line:
                m = re.search(r"Final residual = ([\deE.+-]+), No Iterations (\d+)", line)
                if m:
                    p_fin.append(float(m.group(1))); p_iters.append(int(m.group(2)))
            elif "Courant Number" in line:
                m = re.search(r"max: ([\deE.+-]+)", line)
                if m: co_max = float(m.group(1))
            elif "time step continuity errors" in line:
                m = re.search(r"sum local = ([\deE.+-]+).*cumulative = ([\deE.+-]+)", line)
                if m: cont_local, cont_cum = float(m.group(1)), float(m.group(2))
            elif line.startswith("ExecutionTime"):
                m = re.search(r"ExecutionTime = ([\deE.+-]+)", line)
                if m: exec_s = float(m.group(1))
    med = lambda a: float(np.median(a)) if a else float("nan")
    return dict(steps_done=n_t, ux_lines=ux, uy_lines=uy, Co_max=co_max,
                exec_s=exec_s, cont_err_local=cont_local, cont_err_cumulative=cont_cum,
                p_iters_median=med(p_iters), p_finalres_median=med(p_fin),
                p_iters_capped=sum(1 for i in p_iters if i >= 1000))


def read_ux_field(path, ncells):
    body = open(path).read().split("internalField", 1)[1].split("boundaryField", 1)[0]
    return np.array([float(v) for v in re.findall(
        r"\(\s*([-\deE.+]+)\s+[-\deE.+]+\s+[-\deE.+]+\s*\)", body)][:ncells])


def accuracy(case):
    """Outlet metrics at the latest time (same definitions as the earlier study)."""
    times = []
    for d in os.listdir(case):
        try: times.append((float(d), d))
        except ValueError: pass
    if len(times) < 1: return {}
    latest = sorted(times)[-1][1]
    f = os.path.join(case, latest, "U")
    if not os.path.exists(f): return {}
    try:
        ux = read_ux_field(f, NX * NY)
    except Exception:
        return {}
    if ux.size != NX * NY: return {}
    dy = H / NY
    yj = (np.arange(NY) + 0.5) * dy
    col = ux[np.arange(NY) * NX + (NX - 1)]
    uana = UMAX * 4 * yj * (H - yj) / H**2
    return dict(U_peak_outlet=float(col.max()),
                U_centre_outlet=float(0.5 * (col[NY//2 - 1] + col[NY//2])),
                U_mean_outlet=float(col.mean()),
                err_max_pct_Umax=float(np.abs(col - uana).max() / UMAX * 100),
                err_L2_pct_Umax=float(np.sqrt(np.mean((col - uana)**2)) / UMAX * 100),
                tau_w_over_rho=float(NU * 0.5 * (col[0] + col[-1]) / (0.5 * dy)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--label", required=True)
    ap.add_argument("--precision", choices=["fp32", "fp64", "fp64ctl"], required=True)
    ap.add_argument("--psolver", choices=["GAMG", "PCG"], default="GAMG")
    ap.add_argument("--ptol", default="1e-06")
    ap.add_argument("--steps", type=int, help="run exactly this many timesteps (timing)")
    ap.add_argument("--endTime", type=float, help="physical end time (accuracy)")
    ap.add_argument("--keep", action="store_true", help="keep case dir afterwards")
    a = ap.parse_args()

    endTime = a.endTime if a.endTime else round(a.steps * DT, 12)
    writeInterval = endTime          # write only the final field
    case = gen_case(a.label, a.psolver, a.ptol, endTime, writeInterval)

    # mesh: always the DP blockMesh (mesh files are precision-independent ASCII)
    rc, _, _ = run(case, "fp64", "blockMesh > log.blockMesh 2>&1")  # mesh always via shipped DP
    if rc != 0:
        print(f"{a.label}: blockMesh FAILED"); return

    rc, wall, rss = run(case, a.precision, "icoFoam", capture_mem=True)
    logm = parse_log(os.path.join(case, "log.icoFoam"))
    acc = accuracy(case)

    # ---- validity check ----
    st = logm["steps_done"]
    valid = (st > 0 and logm["ux_lines"] >= 0.9 * st and logm["uy_lines"] >= 0.9 * st)
    row = dict(label=a.label, precision=a.precision, psolver=a.psolver, ptol=a.ptol,
               nx=NX, ny=NY, cells=NX*NY, dt=DT, steps_requested=(a.steps or ""),
               endTime=endTime, wall_s=round(wall, 2), peak_rss_MiB=round(rss, 1),
               s_per_step=(logm["exec_s"]/st if st else float("nan")),
               valid=("yes" if valid else "NO -- MOMENTUM COMPONENT SKIPPED"),
               **logm, **acc)
    new = not os.path.exists(RESULTS)
    with open(RESULTS, "a", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=CSV_FIELDS, extrasaction="ignore")
        if new: w.writeheader()
        w.writerow(row)

    print(f"{a.label} [{a.precision}/{a.psolver} ptol={a.ptol}] "
          f"steps={st} Ux={logm['ux_lines']} Uy={logm['uy_lines']} -> {row['valid']}")
    print(f"   wall={wall:.2f}s exec={logm['exec_s']:.2f}s "
          f"({row['s_per_step']:.4f} s/step) peakRSS={rss:.1f} MiB "
          f"Co_max={logm['Co_max']:.4f}")
    print(f"   p-iters median={logm['p_iters_median']:.0f} capped={logm['p_iters_capped']} "
          f"finalres median={logm['p_finalres_median']:.2e} "
          f"cont(local/cum)={logm['cont_err_local']:.2e}/{logm['cont_err_cumulative']:.2e}")
    if acc:
        print(f"   U_peak={acc['U_peak_outlet']:.6f} errL2={acc['err_L2_pct_Umax']:.5f}% "
              f"tau_w={acc['tau_w_over_rho']:.6f}")
    if not a.keep:
        for d in os.listdir(case):
            if d not in ("0", "constant", "system") and os.path.isdir(os.path.join(case, d)):
                pass  # keep final time dir for accuracy; nothing to prune here


if __name__ == "__main__":
    main()
